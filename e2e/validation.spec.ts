import { rules, schemas, validateAll, validateField } from "../lib/validation";
import { expect, gotoHome, test } from "./fixtures";

test.describe("validation rules (unit)", () => {
  test.skip(({ isMobile }) => isMobile, "pure logic — run once");

  test("email: optional, but must look valid when filled", () => {
    const email = rules.email();
    for (const ok of ["", "a@b.ua", "olena.k+wine@gmail.com", "x@sub.domain.com.ua", "ім'я@пошта.укр"]) expect(email(ok), ok).toBeNull();
    for (const bad of ["a", "a@", "@b.ua", "a@b", "a@b.c", "a b@c.ua", "a@@b.ua", "a@b..ua"]) expect(email(bad), bad).not.toBeNull();
  });

  test("phone / contact: required but any non-blank text is fine", () => {
    expect(validateField(schemas.booking, "contact", "   ")).toBe("Вкажіть телефон або месенджер, щоб я міг з вами зв'язатися");
    expect(validateField(schemas.booking, "contact", "@olena")).toBeNull();
    expect(validateField(schemas["book-preorder"], "phone", "+380 50 111 22 33")).toBeNull();
  });

  test("name: required, at least 2 characters, at most 100", () => {
    expect(validateField(schemas.contact, "name", "")).toBe("Вкажіть ваше ім'я");
    expect(validateField(schemas.contact, "name", " A ")).toBe("Ім'я занадто коротке");
    expect(validateField(schemas.contact, "name", "Al")).toBeNull();
    expect(validateField(schemas.contact, "name", "x".repeat(101))).toMatch(/максимум 100/);
  });

  test("validateAll reports every wrong field at once", () => {
    expect(Object.keys(validateAll(schemas["book-preorder"], { name: "", phone: " ", email: "nope" }))).toEqual(["name", "phone", "email"]);
    expect(validateAll(schemas["book-preorder"], { name: "Ірина", phone: "@irina", email: "" })).toEqual({});
  });
});

test("empty booking popup shows errors, focuses the first field and sends nothing", async ({ page, formMock }) => {
  await gotoHome(page);
  await page.locator("#spec-fromagier").getByRole("button").click();
  const dialog = page.getByRole("dialog", { name: "Швидке замовлення" });
  await dialog.getByRole("button", { name: "Підтвердити заявку" }).click();

  const name = dialog.getByLabel("Ваше ім'я *");
  const contact = dialog.getByLabel("Телефон / Messenger *");
  await expect(name).toBeFocused();
  await expect(name).toHaveAttribute("aria-invalid", "true");
  await expect(name).toHaveAccessibleDescription("Вкажіть ваше ім'я");
  // Red border (catches the class not being generated by Tailwind).
  await expect(contact).toHaveCSS("border-top-color", "rgba(248, 113, 113, 0.8)");
  await expect(contact).toHaveAccessibleDescription(/Вкажіть телефон або месенджер/);
  expect(formMock.requests).toHaveLength(0);

  // Errors update live once shown.
  await name.fill("Олена");
  await expect(name).not.toHaveAttribute("aria-invalid", "true");
  await contact.fill("   ");
  await dialog.getByRole("button", { name: "Підтвердити заявку" }).click();
  await expect(contact).toBeFocused();
  expect(formMock.requests).toHaveLength(0);

  await contact.fill("@olena");
  await dialog.getByRole("button", { name: "Підтвердити заявку" }).click();
  await expect(dialog.getByRole("status")).toBeVisible();
  expect(formMock.requests).toHaveLength(1);
});

test("book form: wrong email is caught on blur and blocks sending; empty email is fine", async ({ page, formMock }) => {
  await gotoHome(page);
  const s = page.locator("#book");
  await s.getByLabel("Ім'я *").fill("Ірина");
  await s.getByLabel("Телефон / Telegram *").fill("@irina");
  const email = s.getByLabel("Email (необов'язково)");
  await email.fill("irina@gmail");
  await email.blur();
  await expect(email).toHaveAccessibleDescription("Перевірте email — схоже, в адресі помилка");

  await s.getByRole("button", { name: "Залишити заявку на книгу" }).click();
  await expect(email).toBeFocused();
  expect(formMock.requests).toHaveLength(0);

  await email.fill("");
  await expect(email).not.toHaveAttribute("aria-invalid", "true");
  await s.getByRole("button", { name: "Залишити заявку на книгу" }).click();
  await expect(s.getByRole("status")).toBeVisible();
  expect(formMock.requests).toEqual([{ form: "book-preorder", name: "Ірина", phone: "@irina" }]);
});

